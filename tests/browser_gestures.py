"""Regression cases invoked by browser_smoke.py; no extra dependencies."""
import copy


def run_gesture_tests(browser, base, data):
    errors = []
    page = browser.new_page(viewport={'width': 1366, 'height': 900})
    page.on('pageerror', lambda error: errors.append(str(error)))
    kingdom = '[data-place-id="demo-kingdom-01"]'
    city = '[data-place-id="demo-city-01"]'

    def open_map(fragment=''):
        page.goto(base + fragment)
        page.wait_for_selector('.map-place')
        page.locator('#reset').click()

    def center(selector):
        bounds = page.locator(selector).bounding_box()
        return bounds['x'] + bounds['width'] / 2, bounds['y'] + bounds['height'] / 2

    def transform(target=page):
        return target.locator('#map-scene').get_attribute('transform')

    def select(selector):
        page.locator(selector).click()
        page.wait_for_function('location.hash.includes("/place/")')

    # A short click or a tiny jitter selects, with capture on the place itself.
    open_map()
    select(kingdom)
    assert page.locator('#place-name').inner_text() == 'Regno dimostrativo 01'
    open_map()
    x, y = center(kingdom + ' rect')
    initial = transform()
    page.mouse.move(x, y); page.mouse.down()
    page.mouse.move(x + 2, y + 1); page.mouse.up()
    page.wait_for_function('location.hash.includes("/place/demo-kingdom-01")')
    assert transform() == initial, 'jitter must not pan'

    # Fast AND slow drags, starting on both region areas and city pins.
    for fragment, selector in [('', kingdom + ' rect'), ('#/map/demo-map-kingdom-01', city + ' circle')]:
        for steps in [1, 60]:
            open_map(fragment)
            x, y = center(selector)
            original_hash = page.evaluate('location.hash')
            initial = transform()
            page.mouse.move(x, y); page.mouse.down()
            page.mouse.move(x + 30, y + 15, steps=steps); page.mouse.up()
            assert transform() != initial, (selector, steps, 'did not pan')
            # First threshold crossing must include the accumulated displacement.
            translation = page.locator('#map-scene').evaluate('(el) => {const m=el.transform.baseVal.consolidate().matrix; return [m.e,m.f]}')
            expected = page.locator('#viewport').evaluate('(el) => {const m=el.getScreenCTM().inverse(); return [30*m.a,15*m.d]}')
            assert all(abs(a-b) < .1 for a, b in zip(translation, expected)), (translation, expected)
            page.wait_for_timeout(50)
            assert page.evaluate('location.hash') == original_hash, 'drag selected a place'
            page.locator('#reset').click()
            select(selector.rsplit(' ', 1)[0])

    # A drag remains a drag even if it returns to its starting point.
    open_map()
    x, y = center(kingdom + ' rect')
    page.mouse.move(x, y); page.mouse.down()
    page.mouse.move(x + 30, y); page.mouse.move(x, y); page.mouse.up()
    assert page.evaluate('location.hash') == ''

    # Cancelling or losing real pointer capture must stop movement, suppress click
    # and leave the next gesture functional. pointercancel is injected explicitly;
    # lostpointercapture is generated by releasing the browser's capture.
    for termination, dragging in [(kind, active) for kind in ['pointercancel', 'lostpointercapture'] for active in [False, True]]:
        open_map()
        page.locator(kingdom).evaluate('el => el.addEventListener("pointerdown", e => window.testPointerId=e.pointerId, {once:true})')
        x, y = center(kingdom + ' rect')
        page.mouse.move(x, y); page.mouse.down()
        assert page.locator(kingdom).evaluate('el => el.hasPointerCapture(window.testPointerId)')
        if dragging:
            page.mouse.move(x + 10, y + 5)
        if termination == 'pointercancel':
            page.locator(kingdom).evaluate('el => el.dispatchEvent(new PointerEvent("pointercancel", {bubbles:true, pointerId:window.testPointerId}))')
        else:
            page.locator(kingdom).evaluate('el => el.releasePointerCapture(window.testPointerId)')
        initial = transform()
        page.mouse.move(x + 20, y + 10); page.mouse.up()
        assert transform() == initial, termination
        assert page.evaluate('location.hash') == '', termination
        select(kingdom)

    # Desktop zoom still preserves the map point under the cursor.
    open_map()
    x, y = center(kingdom + ' rect')
    x, y = round(x), round(y)  # Wheel coordinates are integral CSS pixels.
    def map_point():
        return page.locator('#map-scene').evaluate('(el,p) => {const q=new DOMPoint(...p).matrixTransform(el.getScreenCTM().inverse()); return [q.x,q.y]}', [x, y])
    before = map_point()
    page.mouse.move(x, y); page.mouse.wheel(0, -100)
    page.wait_for_function('document.querySelector("#zoom-value").value !== "100%"')
    after = map_point()
    assert all(abs(a-b) < .1 for a,b in zip(before, after)), (before, after, x, y, transform())

    # Arbitrary full JSON names wrap within their area and survive zooming.
    custom = copy.deepcopy(data)
    custom['places'][1]['name'] = 'Confederazione delle Terre Settentrionali'
    page.route('**/data/demo/atlas.json', lambda route: route.fulfill(json=custom))
    open_map()
    label = page.locator(kingdom + ' text')
    assert ' '.join(label.locator('tspan').all_text_contents()) == custom['places'][1]['name']
    assert label.evaluate('(el) => {const b=el.getBBox(),r=el.previousElementSibling.getBBox();return b.x>=r.x && b.y>=r.y && b.x+b.width<=r.x+r.width && b.y+b.height<=r.y+r.height}')
    for _ in range(12): page.locator('#plus').click()
    assert page.locator('#zoom-value').inner_text() == '600%'
    assert ' '.join(label.locator('tspan').all_text_contents()) == custom['places'][1]['name']
    for _ in range(12): page.locator('#minus').click()
    assert page.locator('#zoom-value').inner_text() == '70%'

    mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True)
    phone = mobile.new_page()
    phone.on('pageerror', lambda error: errors.append(str(error)))
    cdp = mobile.new_cdp_session(phone)

    def touch(kind, points):
        cdp.send('Input.dispatchTouchEvent', {'type': kind, 'touchPoints': [{'x': x, 'y': y, 'id': i} for i, (x, y) in enumerate(points)]})

    def phone_open(fragment=''):
        phone.goto(base + fragment)
        phone.wait_for_selector('.map-place')

    # A finger starting on a region or pin can pan; a following tap selects.
    for fragment, selector in [('', kingdom + ' rect'), ('#/map/demo-map-kingdom-01', city + ' circle')]:
        phone_open(fragment)
        bounds = phone.locator(selector).bounding_box()
        x, y = bounds['x'] + bounds['width']/2, bounds['y'] + bounds['height']/2
        original_hash = phone.evaluate('location.hash')
        initial = transform(phone)
        touch('touchStart', [(x, y)])
        for delta in range(1, 41): touch('touchMove', [(x + delta, y + delta / 2)])
        touch('touchEnd', [])
        assert transform(phone) != initial
        assert phone.evaluate('location.hash') == original_hash
        phone.locator('#reset').tap()
        phone.locator(selector).tap()
        phone.wait_for_function('location.hash.includes("/place/")')

    # Pinch starting on a region, cancellation, then a clean tap/navigation.
    phone_open()
    bounds = phone.locator(kingdom + ' rect').bounding_box()
    x, y = bounds['x'] + bounds['width']/2, bounds['y'] + bounds['height']/2
    touch('touchStart', [(x-5, y), (x+5, y)])
    touch('touchMove', [(x-25, y), (x+25, y)])
    touch('touchEnd', [])
    assert int(phone.locator('#zoom-value').inner_text().rstrip('%')) > 100
    assert phone.evaluate('location.hash') == ''
    phone.locator('#reset').tap()
    touch('touchStart', [(x, y)]); touch('touchCancel', [])
    initial = transform(phone)
    assert phone.evaluate('location.hash') == ''
    phone.locator(kingdom + ' rect').tap()
    phone.get_by_role('link', name='Esplora il regno →').tap()
    phone.wait_for_selector(city)
    phone.locator(city + ' circle').tap()
    phone.get_by_role('link', name='Apri la mappa della città →').tap()
    phone.wait_for_function('document.querySelector("#map-level").textContent === "Città"')
    assert not errors, errors
    mobile.close()
    page.close()
    print('PASS gesture regressions: click/jitter, region and city drags (fast/slow), no accidental selection, cancel/lost capture recovery, anchored zoom, full labels, touch drag/pinch/cancel and three-level navigation.')
